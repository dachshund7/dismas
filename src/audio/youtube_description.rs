//! The descriptions that YouTube generates for the tracks the labels
//! provide, which downloaders like yt-dlp store in the tags, e.g. as
//! "SYNOPSIS". The other tags of these tracks have little more than the
//! title, the artist and the album, and their date is the one of the
//! upload, but the description has the credits:
//!
//! ```text
//! Provided to YouTube by Warner Classics
//!
//! Variations on an Original Theme, Op. 36 "Enigma" · Sir John Barbirolli
//!
//! British Music. Elgar, Vaughan Williams, Delius, Purcell...
//!
//! ℗ 1963 Parlophone Records Limited. Remastered (p) 2019 Parlophone Records Limited
//!
//! Released on: 2019-03-01
//!
//! Orchestra: Philharmonia Orchestra
//! Conductor: Sir John Barbirolli
//! Composer: Sir Edward Elgar
//!
//! Auto-generated by YouTube.
//! ```

use super::track::{Credit, TrackCredits};

// The credits, dates and copyright in a description, or `None` if the
// text isn't one generated by YouTube
pub fn parse(text: &str) -> Option<TrackCredits> {
    let lines: Vec<&str> = text.lines().map(str::trim).collect();
    if !lines.first()?.starts_with("Provided to YouTube by ") {
        return None;
    }

    let mut credits = TrackCredits::default();

    // The provider, the title with the artists and the album come first,
    // each followed by an empty line
    let body = lines
        .split(|line| line.is_empty())
        .filter(|block| !block.is_empty())
        .skip(3)
        .flatten();
    for line in body {
        if line.starts_with(['℗', '©']) {
            // Some have double spaces, e.g. "℗ 1994  BIS"
            let line = line.split_whitespace().collect::<Vec<_>>().join(" ");
            credits.copyright.push(line);
        } else if let Some(date) = line.strip_prefix("Released on: ") {
            credits.date = Some(date.trim().to_string());
        } else if let Some((roles, name)) = line.split_once(':') {
            let name = name.trim();
            if !name.is_empty() {
                add_credit(&mut credits, roles, name);
            }
        }
    }

    // The recording was first released in the year of the earliest ℗; the
    // release date is often the one of a reissue
    credits.original_date = credits
        .copyright
        .iter()
        .flat_map(|line| phonogram_years(line))
        .min()
        .map(|year| year.to_string());

    Some(credits)
}

// The years after "℗" or "(P)", e.g. 1963 and 2019 in
// "℗ 1963 Parlophone Records Limited. Remastered (p) 2019 Parlophone"
fn phonogram_years(line: &str) -> impl Iterator<Item = u32> + '_ {
    ["℗", "(p)", "(P)"]
        .into_iter()
        .flat_map(|symbol| line.match_indices(symbol))
        .filter_map(|(i, symbol)| {
            let rest = line[i + symbol.len()..].trim_start();
            let year = rest.get(..4)?;
            let is_year = year.bytes().all(|b| b.is_ascii_digit())
                && !rest[4..].starts_with(|c: char| c.is_ascii_digit());
            is_year.then(|| year.parse().ok()).flatten()
        })
}

// Adds a "Role: Name" line; there can be several roles, e.g.
// "Producer, Engineer: Name", and none, e.g. ": Name"
fn add_credit(credits: &mut TrackCredits, roles: &str, name: &str) {
    let roles = split_roles(roles);

    // These only say that the person performs, so the other roles in the
    // line, e.g. "Associated Performer, Piano", say more
    let generic = |role: &str| {
        matches!(
            role,
            "artist" | "associated performer" | "main artist" | "featured artist" | "performer"
        )
    };
    let specific: Vec<&str> = roles
        .iter()
        .map(String::as_str)
        .filter(|role| !generic(role))
        .collect();
    if specific.is_empty() {
        push_credit(&mut credits.performers, name, None);
    }

    for role in specific {
        match role {
            "composer" => push_name(&mut credits.composers, name),
            "lyricist" | "author" | "librettist" | "poet" => {
                push_name(&mut credits.lyricists, name);
            }
            "composer lyricist" => {
                push_name(&mut credits.composers, name);
                push_name(&mut credits.lyricists, name);
            }
            "arranger" | "work arranger" => push_name(&mut credits.arrangers, name),
            "conductor" => push_name(&mut credits.conductors, name),
            "producer" | "studio producer" => push_name(&mut credits.producers, name),
            "engineer" | "recording engineer" | "sound engineer" | "balance engineer" => {
                push_name(&mut credits.engineers, name);
            }
            "mixer" | "mixing engineer" | "mix engineer" => push_name(&mut credits.mixers, name),
            "remixer" => push_name(&mut credits.remixers, name),
            // The publishers of the works, which are often just "n/a" or
            // "Copyright Control"
            "music publisher" => (),
            _ if is_production_role(role) => {
                push_credit(&mut credits.other_production, name, Some(role));
            }
            // Anything else is a performer, like "orchestra", "choir",
            // "soprano" or "harpsichord"
            _ => push_credit(&mut credits.performers, name, Some(role)),
        }
    }
}

fn is_production_role(role: &str) -> bool {
    ["engineer", "producer", "editor", "mastering", "personnel"]
        .iter()
        .any(|word| role.contains(word))
}

// The roles in a credit, in lower case with single spaces; some are
// spelled out with spaces between the letters, e.g. "M U S I C_ P U B L I
// S H E R", and some are missing a space, e.g. "Mezzo- Sopranovocalist"
fn split_roles(roles: &str) -> Vec<String> {
    let words: Vec<&str> = roles.split_whitespace().collect();
    let spelled_out = words.len() > 2 && words.iter().all(|w| w.chars().count() <= 2);
    let roles = if spelled_out {
        words.concat().replace('_', " ")
    } else {
        roles.to_string()
    };

    let roles = roles
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .to_lowercase()
        .replace("- ", "-");

    roles
        .split(',')
        .map(str::trim)
        .filter(|role| !role.is_empty())
        .map(|role| {
            ["vocalist", "arranger"]
                .iter()
                .find_map(|word| {
                    let prefix = role.strip_suffix(word)?;
                    let glued = prefix.ends_with(|c: char| c.is_alphabetic());
                    glued.then(|| format!("{prefix} {word}"))
                })
                .unwrap_or_else(|| role.to_string())
        })
        .collect()
}

fn push_name(names: &mut Vec<String>, name: &str) {
    if !names.iter().any(|n| n == name) {
        names.push(name.to_string());
    }
}

fn push_credit(credits: &mut Vec<Credit>, name: &str, role: Option<&str>) {
    let credit = Credit {
        name: name.to_string(),
        role: role.map(str::to_string),
    };
    if !credits.contains(&credit) {
        credits.push(credit);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn credit(name: &str, role: Option<&str>) -> Credit {
        Credit {
            name: name.to_string(),
            role: role.map(str::to_string),
        }
    }

    #[test]
    fn reads_credits_dates_and_copyright() {
        let text = "Provided to YouTube by Warner Classics

Variations on an Original Theme, Op. 36 \"Enigma\": Variation IV · Sir John Barbirolli

British Music. Elgar, Vaughan Williams, Delius, Purcell...

℗ 1963 Parlophone Records Limited. Remastered (p) 2019 Parlophone Records Limited

Released on: 2019-03-01

Orchestra: Philharmonia Orchestra
Conductor: Sir John Barbirolli
Composer: Sir Edward Elgar

Auto-generated by YouTube.";
        let credits = parse(text).unwrap();
        assert_eq!(credits.date.as_deref(), Some("2019-03-01"));
        assert_eq!(credits.original_date.as_deref(), Some("1963"));
        assert_eq!(
            credits.copyright,
            ["℗ 1963 Parlophone Records Limited. Remastered (p) 2019 Parlophone Records Limited"]
        );
        assert_eq!(credits.composers, ["Sir Edward Elgar"]);
        assert_eq!(credits.conductors, ["Sir John Barbirolli"]);
        assert_eq!(
            credits.performers,
            [credit("Philharmonia Orchestra", Some("orchestra"))]
        );
    }

    #[test]
    fn ignores_other_descriptions() {
        assert!(parse("https://www.youtube.com/watch?v=kmT2kmXTSzM").is_none());
        assert!(parse("").is_none());
    }

    #[test]
    fn skips_the_title_and_album() {
        // The title and the album can look like credits
        let text = "Provided to YouTube by NAXOS of America

Graupner: Partita in F Major · Gianluca Luisi

Chopin: Piano Works

℗ 2020 OnClassical

Artist: Gianluca Luisi";
        let credits = parse(text).unwrap();
        assert!(credits.composers.is_empty());
        assert_eq!(credits.performers, [credit("Gianluca Luisi", None)]);
        assert_eq!(credits.date, None);
    }

    #[test]
    fn splits_multiple_roles() {
        let text = "Provided to YouTube by Naxos Digital Services

Title · Artist

Album

Producer, Mastering Engineer, Sound Editor: Ann
Associated  Performer, Piano: Bob
Associated Performer: Carl
Composer  Lyricist: Dora
M U S I C_ P U B L I S H E R: n/a
C O M P O S E R: Emil
: Fay
Workarranger: Gus
Mezzo- Sopranovocalist: Hana";
        let credits = parse(text).unwrap();
        assert_eq!(credits.producers, ["Ann"]);
        assert_eq!(
            credits.other_production,
            [
                credit("Ann", Some("mastering engineer")),
                credit("Ann", Some("sound editor")),
            ]
        );
        assert_eq!(
            credits.performers,
            [
                credit("Bob", Some("piano")),
                credit("Carl", None),
                credit("Fay", None),
                credit("Hana", Some("mezzo-soprano vocalist")),
            ]
        );
        assert_eq!(credits.arrangers, ["Gus"]);
        assert_eq!(credits.composers, ["Dora", "Emil"]);
        assert_eq!(credits.lyricists, ["Dora"]);
    }

    #[test]
    fn original_year_is_the_first_phonogram_year() {
        let years: Vec<u32> =
            phonogram_years("℗ A Warner Classics release, ℗ 1971 Parlophone. Remastered (P) 2020")
                .collect();
        assert_eq!(years, [1971, 2020]);
        assert_eq!(phonogram_years("℗ Brilliant Classics").count(), 0);
        assert_eq!(phonogram_years("℗ 19945 Nobody").count(), 0);
    }
}
